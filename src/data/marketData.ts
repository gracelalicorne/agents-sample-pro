// Helper to generate realistic random walk time series chart points
function generateChartPoints(basePrice: number, pointsCount: number, volatility: number, isBullish: boolean): any[] {
  const points = [];
  let currentPrice = basePrice * (isBullish ? 0.985 : 1.015);
  const now = new Date();
  
  for (let i = pointsCount; i >= 0; i--) {
    const time = new Date(now.getTime() - i * 15 * 60 * 1000);
    const timeStr = time.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    
    const delta = (Math.random() - (isBullish ? 0.45 : 0.55)) * volatility * basePrice;
    currentPrice += delta;
    
    // ensure price stays reasonable
    if (currentPrice <= 0) currentPrice = basePrice * 0.1;
    
    points.push({
      time: timeStr,
      value: parseFloat(currentPrice.toFixed(2)),
      open: parseFloat((currentPrice * 0.999).toFixed(2)),
      high: parseFloat((currentPrice * 1.002).toFixed(2)),
      low: parseFloat((currentPrice * 0.998).toFixed(2)),
      close: parseFloat(currentPrice.toFixed(2)),
      volume: Math.floor(Math.random() * 50000) + 10000
    });
  }
  return points;
}

